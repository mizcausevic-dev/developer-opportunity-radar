  codeRepository: 'https://github.com/mizcausevic-dev/developer-opportunity-radar',
  dateModified: snap.generated_at.slice(0, 10),
  publisher: { '@type': 'Organization', name: 'Kinetic Gain', url: 'https://kineticgain.com/' },
