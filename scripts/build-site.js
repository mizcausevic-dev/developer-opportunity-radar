// ---------------------------------------------------------------- Content-Security-Policy
// Pages can't send headers, so the policy ships as a <meta>. Inline scripts are allowed only
// by hash (computed from the final HTML), fetches only to this site and the demo API.
// frame-ancestors is not honoured in <meta>; GitHub Pages' own headers apply there.
function withCsp(page) {
  const inline = /<script(?![^>]*\bsrc=)(?![^>]*application\/ld\+json)[^>]*>([\s\S]*?)<\/script>/g;
  const hashes = [...page.matchAll(inline)].map((m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`);
  const policy = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    `connect-src 'self' ${new URL(API_BASE).origin}`,
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  const charset = '<meta charset="utf-8">';
  if (!page.includes(charset)) throw new Error('withCsp: charset meta not found');
  return page.replace(charset, `${charset}\n<meta http-equiv="Content-Security-Policy" content="${policy}">`);
}

