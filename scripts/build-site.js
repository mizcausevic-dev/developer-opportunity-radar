// ---------------------------------------------------------------- api.html
const resolve = (obj) => {
  if (!obj || !obj.$ref) return obj;
  return obj.$ref.slice(2).split('/').reduce((o, k) => o[k], spec);
};
const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (method === 'parameters') continue;
    ops.push({ path, method: method.toUpperCase(), op, params: [...(item.parameters ?? []), ...(op.parameters ?? [])].map(resolve) });
  }
}
const anchor = (o) => o.op.operationId;
const opHtml = (o) => {
  const params = o.params.length
    ? `<div class="table-wrap"><table class="data"><thead><tr><th>Name</th><th>In</th><th>Schema</th><th>Description</th></tr></thead><tbody>${o.params
        .map((p) => `<tr><td><code>${esc(p.name)}</code>${p.required ? ' *' : ''}</td><td>${esc(p.in)}</td><td><code>${esc(schemaText(p.schema))}</code></td><td style="white-space:normal">${esc(p.description ?? '')}</td></tr>`)
        .join('')}</tbody></table></div>`
    : '';
  const body = o.op.requestBody
    ? `<p class="sum"><b>Body</b> (optional, application/json): <code>${esc(JSON.stringify(Object.fromEntries(Object.entries(o.op.requestBody.content['application/json'].schema.properties).map(([k, v]) => [k, schemaText(v)]))))}</code></p>`
    : '';
  const resps = Object.entries(o.op.responses)
    .map(([code, r]) => `<span class="chip" title="${esc(resolve(r).description)}">${esc(code)} ${esc(code === 'default' ? 'problem+json' : resolve(r).description)}</span>`)
    .join('');
  const example = `curl -i ${o.method === 'GET' ? '' : `-X ${o.method} -H 'Authorization: Bearer $RADAR_API_KEY' `}'${API_BASE}${o.path.replace('{owner}', 'expressjs').replace('{name}', 'express').replace('{id}', o.path.includes('jobs') ? 'job_…' : o.path.includes('issues/{id}') ? 'iss_…' : 'cl_…')}'`;
  return `<article class="op" id="${esc(anchor(o))}">
  <h3><span class="verb ${o.method}">${o.method}</span>${esc(o.path)}${o.op.security ? '<span class="lock">· requires API key</span>' : ''}</h3>
  <p class="sum"><b>${esc(o.op.summary)}</b></p>
  ${o.op.description ? `<p class="sum">${esc(o.op.description)}</p>` : ''}
  ${params}${body}
  <div class="resp">${resps}</div>
  <pre class="ex">${esc(example)}</pre>
</article>`;
};
function schemaText(s) {
  if (!s) return '';
  const parts = [s.type ? [].concat(s.type).join('|') : ''];
  if (s.enum) parts.push(`enum: ${s.enum.join(', ')}`);
  if (s.minimum !== undefined || s.maximum !== undefined) parts.push(`${s.minimum ?? ''}..${s.maximum ?? ''}`);
  if (s.pattern) parts.push(`/${s.pattern}/`);
  if (s.default !== undefined) parts.push(`default ${s.default}`);
  return parts.filter(Boolean).join(' · ');
}
const conventions = spec.info.description
