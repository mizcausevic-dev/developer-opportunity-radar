// ---------------------------------------------------------------- compact dataset
const repos = snap.repositories.map((r) => r.full_name);
const repoIdx = new Map(repos.map((r, i) => [r, i]));
const issuesById = new Map(snap.issues.map((i) => [i.id, i]));
const clusteredIds = [...new Set(snap.clusters.flatMap((c) => c.members.map((m) => m.issue_id)))];
const issueIdx = new Map(clusteredIds.map((id, i) => [id, i]));
const issues = clusteredIds.map((id) => {
  const i = issuesById.get(id);
  const derived = `https://github.com/${i.repository}/issues/${i.number}`;
  if (i.html_url !== derived) throw new Error(`Source URL for ${id} is ${i.html_url}, not ${derived}; the dashboard derives URLs and would break the source link.`);
  return [repoIdx.get(i.repository), i.number, i.title, i.state === 'open' ? 1 : 0, i.created_at.slice(0, 10)];
});

const clusters = snap.clusters.map((c) => {
  const by = repos.map(() => 0);
  for (const m of c.members) by[repoIdx.get(issuesById.get(m.issue_id).repository)] += 1;
  return {
    id: c.id,
    label: c.label,
    terms: c.terms,
    size: c.size,
    rc: c.repo_count,
    by,
    open: c.open_count,
    eng: c.engagement,
    score: c.score,
    comp: c.score_components,
    coh: c.cohesion,
    recent: c.recent_opened ?? 0,
    first: c.first_seen.slice(0, 10),
    last: c.last_seen.slice(0, 10),
    members: c.members.map((m) => issueIdx.get(m.issue_id)),
    titles: c.members.map((m) => issuesById.get(m.issue_id).title).join(' | '),
  };
});

const months = new Map();
for (const i of snap.issues) {
  const m = i.created_at.slice(0, 7);
  const row = months.get(m) ?? [m, 0, 0];
  row[1] += 1;
  if (i.state === 'open') row[2] += 1;
  months.set(m, row);
}
const monthly = [...months.values()].sort((a, b) => (a[0] < b[0] ? -1 : 1));

const repoRows = snap.repositories.map((r) => {
  const mine = snap.issues.filter((i) => i.repository === r.full_name);
  const oldestUpdated = Math.min(...mine.map((i) => Date.parse(i.updated_at)));
  return {
    name: r.full_name,
    stars: r.stars,
    url: r.html_url,
    issues: mine.length,
    open: mine.filter((i) => i.state === 'open').length,
    covers_days: Math.floor((Date.parse(snap.generated_at) - oldestUpdated) / 86_400_000),
  };
});

const data = {
  generated_at: snap.generated_at,
  threshold: snap.analysis.params.threshold,
  weights: snap.analysis.params.weights ?? DEFAULTS.weights,
  repos: repoRows,
  clusters,
  issues,
  monthly,
  recent_days: snap.analysis.params.recent_days ?? DEFAULTS.recentDays,
  // GET operations from the OpenAPI contract, for the console's parameter builder.
  ops: Object.entries(spec.paths).flatMap(([path, item]) =>
    item.get
      ? [{
          path,
          summary: item.get.summary,
          params: [...(item.parameters ?? []), ...(item.get.parameters ?? [])]
            .map((p) => (p.$ref ? p.$ref.slice(2).split('/').reduce((o, k) => o[k], spec) : p))
            .filter((p) => p.in === 'path' || p.in === 'query')
            .map((p) => ({ name: p.name, in: p.in, required: Boolean(p.required), enum: p.schema?.enum ?? null, min: p.schema?.minimum ?? null, max: p.schema?.maximum ?? null, def: p.schema?.default ?? null, description: p.description ?? '' })),
        }]
      : [],
  ),
};
const dataJs = `/* Generated by scripts/build-site.js from data/snapshot.json. Do not edit. */\nwindow.RADAR = ${JSON.stringify(data)};\n`;
