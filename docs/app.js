  /* ---------------- explorer ---------------- */
  var repoSel = $('#f-repo');
  D.repos.forEach(function (r, j) { var o = document.createElement('option'); o.value = j; o.textContent = r.name; repoSel.appendChild(o); });
  var current = null;
  function filtered() {
    var q = $('#f-q').value.trim().toLowerCase();
    var min = Number($('#f-min').value);
    var repo = repoSel.value === '' ? -1 : Number(repoSel.value);
    var sort = $('#f-sort').value;
    var out = D.clusters.filter(function (c) {
      if (c.rc < min) return false;
      if (repo >= 0 && !c.by[repo]) return false;
      if (q && (c.label + ' ' + c.terms.join(' ') + ' ' + c.titles).toLowerCase().indexOf(q) === -1) return false;
      return true;
    });
    out.sort(function (a, b) {
      if (sort === 'size') return b.size - a.size || b.score - a.score;
      if (sort === 'recent') return a.last < b.last ? 1 : a.last > b.last ? -1 : 0;
      return b.score - a.score;
    });
    return out;
  }
  function renderList() {
    var list = filtered();
    $('#f-count').textContent = list.length + ' cluster' + (list.length === 1 ? '' : 's');
    var ul = $('#clist');
    ul.innerHTML = list.map(function (c) {
      return '<li><button type="button" data-id="' + c.id + '"' + (current === c.id ? ' aria-current="true"' : '') + '>' +
        '<span class="lab">' + esc(c.label) + '</span><span class="sc">' + c.score.toFixed(1) + '</span>' +
        '<span class="bar-mini"><i style="width:' + c.score + '%"></i></span>' +
        '<span class="sub"><span>' + c.size + ' issues</span><span>' + c.rc + ' repo' + (c.rc === 1 ? '' : 's') + '</span><span>' + c.open + ' open</span><span>last ' + c.last + '</span></span></button></li>';
    }).join('') || '<li class="muted" style="padding:14px">No clusters match these filters.</li>';
    if (list.length && !list.some(function (c) { return c.id === current; })) selectCluster(list[0].id, false);
  }
  $('#clist').addEventListener('click', function (e) {
    var b = e.target.closest('button[data-id]');
    if (b) selectCluster(b.getAttribute('data-id'), false);
  });
  ['#f-q', '#f-min', '#f-sort'].forEach(function (s) { $(s).addEventListener('input', renderList); });
  repoSel.addEventListener('input', renderList);

  function selectCluster(id, scroll) {
    var c = D.clusters.find(function (x) { return x.id === id; });
    if (!c) return;
    current = id;
    if (scroll) {
      if (c.rc < Number($('#f-min').value)) $('#f-min').value = '1';
      $('#f-q').value = ''; repoSel.value = '';
      renderList();
    }
    document.querySelectorAll('#clist button').forEach(function (b) { b.setAttribute('aria-current', b.getAttribute('data-id') === id ? 'true' : 'false'); });
    renderDetail(c);
    try { history.replaceState(null, '', '#cluster=' + id); } catch (e) { /* file:// */ }
    if (scroll) document.getElementById('explorer').scrollIntoView({ behavior: 'smooth', block: 'start' });
  }

